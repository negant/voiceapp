#!/usr/bin/env node
/**
 * Generate Android upload keystore for Play Console (local only — never commit).
 * Usage: npm run android:keystore
 */
import { existsSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomBytes, randomInt } from 'node:crypto';
import { execFileSync } from 'node:child_process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const appDir = resolve(root, 'android/app');
const keystorePath = resolve(appDir, 'voiceapp-upload.keystore');
const propsPath = resolve(root, 'android/keystore.properties');

if (existsSync(keystorePath) || existsSync(propsPath)) {
  console.error(
    'Keystore or android/keystore.properties already exists — refusing to overwrite.',
  );
  process.exit(1);
}

const password = randomBytes(18).toString('base64url');
const alias = 'voiceapp-upload';
const dname = 'CN=Voice App, OU=Mobile, O=ukrywane, L=Warsaw, ST=Mazowieckie, C=PL';

execFileSync(
  'keytool',
  [
    '-genkeypair',
    '-v',
    '-storetype',
    'PKCS12',
    '-keystore',
    keystorePath,
    '-alias',
    alias,
    '-keyalg',
    'RSA',
    '-keysize',
    '2048',
    '-validity',
    '10000',
    '-storepass',
    password,
    '-keypass',
    password,
    '-dname',
    dname,
  ],
  { stdio: 'inherit' },
);

writeFileSync(
  propsPath,
  [
    '# Generated by npm run android:keystore — DO NOT COMMIT',
    `storeFile=voiceapp-upload.keystore`,
    `storePassword=${password}`,
    `keyAlias=${alias}`,
    `keyPassword=${password}`,
    '',
  ].join('\n'),
  { mode: 0o600 },
);

console.log('');
console.log('Created:');
console.log(`  ${keystorePath}`);
console.log(`  ${propsPath}`);
console.log('Back up the keystore + passwords offline. Losing them blocks app updates.');
console.log(`Hint seed: ${randomInt(1e6)}`);
